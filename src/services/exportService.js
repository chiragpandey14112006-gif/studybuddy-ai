/**
 * Export Service
 * Enables downloading quiz results and study notes in PDF and TXT formats.
 */

import { jsPDF } from 'jspdf';

/**
 * Triggers a browser download of a text blob
 */
function triggerDownload(blob, filename) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Cleans string for safe filenames
 */
function sanitizeFilename(str) {
  return (str || 'Quiz_Result')
    .replace(/[^a-zA-Z0-9_-]/g, '_')
    .substring(0, 30);
}

/**
 * Export Quiz Attempt as a clean formatted .txt document
 */
export function downloadResultAsTXT(attempt) {
  const dateStr = new Date(attempt.timestamp || Date.now()).toLocaleString();
  const safeTopic = sanitizeFilename(attempt.topic);
  const filename = `StudyBuddy_${safeTopic}_${new Date().toISOString().split('T')[0]}.txt`;

  const durationMin = Math.floor((attempt.durationSeconds || 0) / 60);
  const durationSec = (attempt.durationSeconds || 0) % 60;

  let content = `========================================================================
             STUDYBUDDY AI — ACADEMIC QUIZ REPORT & STUDY NOTES
========================================================================

Subject / Topic : ${attempt.topic || 'General Studies'}
Difficulty Tier : ${attempt.difficulty || 'Intermediate'}
Date Completed  : ${dateStr}
Final Score     : ${attempt.score} / ${attempt.totalQuestions} (${attempt.percentage}%)
Time Elapsed    : ${durationMin}m ${durationSec}s
Proficiency     : ${attempt.percentage >= 80 ? 'Mastery' : attempt.percentage >= 60 ? 'Passing / Review Needed' : 'Needs Reinforcement'}

========================================================================
                      DETAILED QUESTION BREAKDOWN
========================================================================
`;

  const answers = attempt.userAnswers || [];

  answers.forEach((ans, index) => {
    const status = ans.isCorrect ? '[ PASS - CORRECT ]' : '[ REVIEW - MISSED ]';
    content += `\nQuestion ${index + 1}: ${ans.questionText}\n`;
    content += `Status      : ${status}\n`;
    
    if (ans.options && ans.options.length > 0) {
      content += `Options     :\n`;
      ans.options.forEach((opt, oIdx) => {
        const marker = oIdx === ans.correctOptionIndex 
          ? '  (✓ Correct) ' 
          : oIdx === ans.selectedOptionIndex 
          ? '  (✗ Your Pick)' 
          : '              ';
        content += `${marker} [${oIdx + 1}] ${opt}\n`;
      });
    }

    content += `Your Answer : ${ans.options ? ans.options[ans.selectedOptionIndex] : ans.selectedOptionIndex}\n`;
    content += `Correct Key : ${ans.options ? ans.options[ans.correctOptionIndex] : ans.correctOptionIndex}\n`;
    content += `Explanation : ${ans.explanation}\n`;
    content += `------------------------------------------------------------------------\n`;
  });

  content += `\nGenerated by StudyBuddy AI • Active Recall & Spaced Repetition Notebook\n`;

  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  triggerDownload(blob, filename);
}

/**
 * Export Quiz Attempt as a styled Academic PDF document
 */
export function downloadResultAsPDF(attempt) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 15;
  const contentWidth = pageWidth - margin * 2;

  let y = 18;

  // Header Banner: Aesthetic collegiate minimal style
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(30, 41, 59); // Charcoal #1E293B
  doc.text('StudyBuddy AI — Academic Quiz Review', margin, y);
  
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139); // Slate #64748B
  doc.text('Active Recall & Longitudinal Performance Report', margin, y + 5);

  y += 12;

  // Divider line
  doc.setDrawColor(226, 232, 240); // #E2E8F0
  doc.setLineWidth(0.4);
  doc.line(margin, y, pageWidth - margin, y);

  y += 7;

  // Metadata Card Box (light cream/gray fill)
  doc.setFillColor(248, 250, 252);
  doc.roundedRect(margin, y, contentWidth, 24, 3, 3, 'F');
  doc.setDrawColor(226, 232, 240);
  doc.roundedRect(margin, y, contentWidth, 24, 3, 3, 'S');

  doc.setFontSize(9);
  doc.setTextColor(51, 65, 85);
  doc.text(`Subject: ${attempt.topic || 'General'}`, margin + 4, y + 7);
  doc.text(`Difficulty: ${attempt.difficulty || 'Intermediate'}`, margin + 4, y + 14);
  doc.text(`Date: ${new Date(attempt.timestamp || Date.now()).toLocaleDateString()}`, margin + 4, y + 21);

  // Score stats on right side of card
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  const pct = Number(attempt.percentage) || 0;
  if (pct >= 80) {
    doc.setTextColor(16, 185, 129); // Emerald
  } else if (pct >= 50) {
    doc.setTextColor(79, 70, 229); // Indigo
  } else {
    doc.setTextColor(225, 29, 72); // Rose
  }
  doc.text(`${pct}% Accuracy`, pageWidth - margin - 40, y + 10);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text(`Score: ${attempt.score} / ${attempt.totalQuestions}`, pageWidth - margin - 40, y + 16);
  doc.text(`Time: ${Math.floor((attempt.durationSeconds || 0) / 60)}m ${(attempt.durationSeconds || 0) % 60}s`, pageWidth - margin - 40, y + 21);

  y += 32;

  // Section Header
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(30, 41, 59);
  doc.text('Question Breakdown & Didactic Explanations', margin, y);
  y += 6;

  const answers = attempt.userAnswers || [];

  answers.forEach((ans, index) => {
    // Check if near bottom of page
    if (y > pageHeight - 45) {
      doc.addPage();
      y = 18;
    }

    const isPass = ans.isCorrect;

    // Small status indicator
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9);
    if (isPass) {
      doc.setTextColor(16, 185, 129);
      doc.text(`[ PASS ] Question ${index + 1}`, margin, y);
    } else {
      doc.setTextColor(225, 29, 72);
      doc.text(`[ MISSED ] Question ${index + 1}`, margin, y);
    }

    y += 5;

    // Question Prompt
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9);
    doc.setTextColor(30, 41, 59);
    const qLines = doc.splitTextToSize(ans.questionText, contentWidth);
    doc.text(qLines, margin, y);
    y += qLines.length * 4.5 + 2;

    // User Choice vs Correct Choice
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8.5);
    
    if (ans.options && ans.options[ans.selectedOptionIndex]) {
      if (isPass) {
        doc.setTextColor(22, 101, 52);
      } else {
        doc.setTextColor(153, 27, 27);
      }
      doc.text(`Your choice: ${ans.options[ans.selectedOptionIndex]}`, margin + 3, y);
      y += 4;
    }

    if (!isPass && ans.options && ans.options[ans.correctOptionIndex]) {
      doc.setTextColor(22, 101, 52);
      doc.text(`Correct key: ${ans.options[ans.correctOptionIndex]}`, margin + 3, y);
      y += 4;
    }

    // Explanation Box
    if (ans.explanation) {
      doc.setTextColor(100, 116, 139);
      const expText = `Explanation: ${ans.explanation}`;
      const expLines = doc.splitTextToSize(expText, contentWidth - 4);
      
      // Draw background tint for explanation
      const boxHeight = expLines.length * 4 + 3;
      doc.setFillColor(248, 250, 252);
      doc.roundedRect(margin, y, contentWidth, boxHeight, 1.5, 1.5, 'F');
      
      doc.text(expLines, margin + 2, y + 3.5);
      y += boxHeight + 4;
    } else {
      y += 3;
    }

    // Dotted separator line
    doc.setDrawColor(241, 245, 249);
    doc.setLineDashPattern([1, 1], 0);
    doc.line(margin, y, pageWidth - margin, y);
    doc.setLineDashPattern([], 0);

    y += 5;
  });

  // Footer on last page
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.text(`StudyBuddy AI • Generated on ${new Date().toLocaleDateString()}`, margin, pageHeight - 8);

  const safeTopic = sanitizeFilename(attempt.topic);
  const filename = `StudyBuddy_${safeTopic}_${new Date().toISOString().split('T')[0]}.pdf`;
  doc.save(filename);
}
